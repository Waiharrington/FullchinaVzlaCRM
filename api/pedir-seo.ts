import { createClient } from '@supabase/supabase-js'

const SITE_ORIGIN = 'https://fullchinavzla.vercel.app'
const PUBLIC_MENU_URL = `${SITE_ORIGIN}/pedir`
const SOCIAL_IMAGE_URL = `${SITE_ORIGIN}/social/pedir-full-china.jpg`
const environment = (globalThis as typeof globalThis & { process?: { env?: Record<string, string | undefined> } }).process?.env ?? {}

type CatalogRow = {
  id?: unknown
  name?: unknown
  description?: unknown
  category?: unknown
  image_url?: unknown
}

type MenuItem = { name: string; description: string; category: string; imageUrl: string | null }

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, character => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character] ?? character)
}

function xmlEscape(value: string): string {
  return value.replace(/[&<>"']/g, character => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' })[character] ?? character)
}

function absoluteImageUrl(value: unknown, productId: string): string | null {
  if (typeof value !== 'string' || !value.trim()) return null
  if (value.startsWith('data:image/')) {
    // The public menu displays uploaded data-URL photos directly. For search
    // engines, use the optimized static copy generated by this repository.
    if (/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(productId)) {
      return new URL(`/optimized/productos/${productId}.webp`, SITE_ORIGIN).toString()
    }
    return null
  }
  if (value.startsWith('data:')) return null
  const path = value.trim().replace(/^\/productos\/([^/?#]+)\.(?:png|jpe?g|webp)([?#].*)?$/i, '/optimized/productos/$1.webp$2')
  try {
    const url = new URL(path, SITE_ORIGIN)
    return url.protocol === 'https:' || url.protocol === 'http:' ? url.toString() : null
  } catch {
    return null
  }
}

async function getPublicMenu(): Promise<MenuItem[]> {
  const supabaseUrl = environment.SUPABASE_URL ?? environment.VITE_SUPABASE_URL
  const anonKey = environment.VITE_SUPABASE_ANON_KEY
  if (!supabaseUrl || !anonKey) return []

  const client = createClient(supabaseUrl, anonKey, {
    db: { schema: 'fullchinavzla' },
    auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false },
  })
  const { data, error } = await client.rpc('fn_get_public_catalog')
  if (error) throw error

  return (Array.isArray(data) ? data as CatalogRow[] : [])
    .map(row => ({
      id: String(row.id ?? ''),
      name: String(row.name ?? '').trim(),
      description: String(row.description ?? '').trim(),
      category: String(row.category ?? 'Menú').trim(),
      imageUrl: absoluteImageUrl(row.image_url, String(row.id ?? '')),
    }))
    .filter(item => item.name)
}

function renderMenuItem(item: MenuItem): string {
  const photo = item.imageUrl
    ? `<img src="${escapeHtml(item.imageUrl)}" alt="Foto de ${escapeHtml(item.name)} de Full China en Maracay" loading="lazy" decoding="async" />`
    : ''
  return `<article class="dish">${photo}<div><p class="category">${escapeHtml(item.category)}</p><h3>${escapeHtml(item.name)}</h3>${item.description ? `<p>${escapeHtml(item.description)}</p>` : ''}</div></article>`
}

