export async function GET(request: Request): Promise<Response> {
  try {
    const items = await getPublicMenu()
    if (new URL(request.url).searchParams.get('format') === 'images') {
      return new Response(imageSitemap(items), {
        headers: { 'Content-Type': 'application/xml; charset=utf-8', 'Cache-Control': 'public, s-maxage=3600, stale-while-revalidate=86400' },
      })
    }
    return new Response(pageHtml(items), {
      headers: {
        'Content-Type': 'text/html; charset=utf-8',
        'Cache-Control': 'public, s-maxage=900, stale-while-revalidate=3600',
        'X-Robots-Tag': 'index, follow, max-image-preview:large',
      },
    })
  } catch (error) {
    console.error('No se pudo cargar el catálogo público para SEO:', error instanceof Error ? error.message : 'error desconocido')
    if (new URL(request.url).searchParams.get('format') === 'images') {
      return new Response(imageSitemap([]), {
        headers: { 'Content-Type': 'application/xml; charset=utf-8', 'Cache-Control': 'public, s-maxage=300' },
      })
    }
    return new Response(pageHtml([]), {
      headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'public, s-maxage=300' },
    })
  }
}

function imageSitemap(items: MenuItem[]): string {
  const images = [...new Map(items.filter(item => item.imageUrl).map(item => [item.imageUrl as string, item])).entries()]
  const entries = [
    `<image:image><image:loc>${xmlEscape(SOCIAL_IMAGE_URL)}</image:loc><image:title>Full China, comida china en Maracay</image:title><image:caption>Portada del menú de pedidos de Full China en Maracay, Estado Aragua</image:caption></image:image>`,
    ...images.map(([url, item]) => `<image:image><image:loc>${xmlEscape(url)}</image:loc><image:title>${xmlEscape(item.name)}</image:title><image:caption>${xmlEscape(item.description || `${item.name} de Full China en Maracay`)}</image:caption></image:image>`),
  ].join('')
  return `<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1"><url><loc>${PUBLIC_MENU_URL}</loc>${entries}</url></urlset>`
}
